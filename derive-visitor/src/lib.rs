/// Defines whether an item is being entered or exited by a visitor.
#[derive(Debug, Clone, Copy)]
pub enum Event {
    Enter,
    Exit,
}

/// Marker types used with [`visitor_fn`] and [`visitor_fn_mut`] to select events.
///
/// Use [`on::Enter`], [`on::Exit`], or [`on::Event`].
pub mod on {
    use std::fmt::Debug;

    #[derive(Debug, Clone, Copy)]
    pub struct Enter;

    #[derive(Debug, Clone, Copy)]
    pub struct Exit;

    #[derive(Debug, Clone, Copy)]
    pub struct Event;

    pub trait On: sealed::Sealed + Debug + Clone + Copy {}

    impl sealed::Sealed for Enter {}
    impl On for Enter {}

    impl sealed::Sealed for Exit {}
    impl On for Exit {}

    impl sealed::Sealed for Event {}
    impl On for Event {}

    mod sealed {
        pub trait Sealed {}
    }
}

/// A data structure that can walk a [visitor](Visitor) through itself.
///
/// Derive or implement this trait for any type that you want to be able to
/// traverse with a visitor.
///
/// `Walk` is implemented for most wrapping and collection types from [std],
/// as long as their wrapped / item type implements `Walk`.
///
/// ## Derivable
///
/// This trait can be derived for any struct or enum.
/// By default, the derived implementation will make the visitor enter `self`,
/// then walk it through every field of `self`, and finally make it exit `self`:
///
/// ```
/// #[derive(Walk)]
/// struct Directory {
///     #[drive(skip)]
///     name: String,
///     items: Vec<DirectoryItem>,
/// }
///
/// #[derive(Walk)]
/// enum DirectoryItem {
///     File(File),
///     Directory(Directory),
/// }
///
/// #[derive(Walk)]
/// struct File {
///     #[drive(skip)]
///     name: String,
/// }
/// ```
///
/// ## Implementing manually
///
/// The following code snippet is roughly equivalent to the implementations
/// that would be derived in the example above:
///
/// ```
/// impl Walk for Directory {
///     fn walk<'visitor, V: Visitor<'visitor> + ?Sized>(&'visitor self, visitor: &mut V) {
///         visitor.enter(self);
///         self.items.walk(visitor);
///         visitor.exit(self);
///     }
/// }
///
/// impl Walk for DirectoryItem {
///     fn walk<'visitor, V: Visitor<'visitor> + ?Sized>(&'visitor self, visitor: &mut V) {
///         visitor.enter(self);
///         match self {
///             Self::File(file) => {
///                 file.walk(visitor);
///             },
///             Self::Directory(directory) => {
///                 directory.walk(visitor);
///             }
///         }
///         visitor.exit(self);
///     }
/// }
///
/// impl Walk for File {
///     fn walk<'visitor, V: Visitor<'visitor> + ?Sized>(&'visitor self, visitor: &mut V) {
///         visitor.enter(self);
///         visitor.exit(self);
///     }
/// }
/// ```
///
/// ## Macro attributes
///
/// The derived implementation of `Walk` can be customized using attributes:
///
/// ### `#[drive(skip)]`
///
/// If applied to a field or an enum variant, the derived implementation won't
/// walk the visitor through that field / variant, or its children.
///
/// ### `#[drive(skip_self)]`
///
/// If applied to a struct or an enum itself, the derived implementation will
/// walk the visitor through the type's child fields / variants, but won't make it
/// enter or exit the type itself.
///
/// ### `#[drive(with="path")]`
///
/// Walk a visitor through a field using a custom function.
/// The function must have the following signature: `fn<V: Visitor<'_> + ?Sized>(&T, &mut V)`.
///
/// In the example below, this attribute is used to customize walking through a [Vec]:
///
/// ```
/// #[derive(Walk)]
/// struct Book {
///     title: String,
///     #[drive(with="reverse_vec_driver")]
///     chapters: Vec<Chapter>,
/// }
///
/// fn reverse_vec_driver<T, V: Visitor<'_> + ?Sized>(vec: &Vec<T>, visitor: &mut V) {
///     for item in vec.iter().rev() {
///         item.walk(visitor);
///     }
/// }
/// ```
pub trait Walk: Any {
    fn walk<'visitor, V: Visitor<'visitor> + ?Sized>(&'visitor self, visitor: &mut V);
}

/// Walk a [`VisitorMut`] over this datastructure.
///
/// This is equivalent to [`Walk`], but gives the possibility to mutate the datastructure as it is visited.
///
/// ## Example
///
/// ```
/// use derive_visitor::{on, visitor_fn_mut, WalkMut};
///
/// #[derive(WalkMut, Default)]
/// struct Node{ children: Vec<Node> }
///
/// let mut node = Node{children: vec![Node::default(), Node::default()]};
///
/// node.walk_mut(&mut visitor_fn_mut(on::Exit, |n: &mut Node| {
///     // Mutate the element on exit so that we are not walked to the newly created elements
///     n.children.resize_with(3, Default::default);
/// }));
///
/// // We have walked over all the initial nodes...
/// assert_eq!(node.children.len(), 3);
/// assert_eq!(node.children[0].children.len(), 3);
/// assert_eq!(node.children[1].children.len(), 3);
/// // ... but not over the newly created ones
/// assert_eq!(node.children[2].children.len(), 0);
/// ```
pub trait WalkMut: Any {
    fn walk_mut<V: VisitorMut + ?Sized>(&mut self, visitor: &mut V);
}

